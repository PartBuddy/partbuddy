#!/usr/bin/env node
// Keeps the website (PartBuddy/partbuddy.github.io) in step with the app; used by
// .github/workflows/site-sync.yml, runnable by hand for a check.
//
//   node tools/site-sync.mjs content <website-dir>
//     copies site/site-content.json (+ schema) to <website-dir>/src/data/ and writes the release
//     snapshot <website-dir>/src/data/releases.json from the GitHub API (GITHUB_TOKEN, read).
//   node tools/site-sync.mjs pr <website-dir> <branch> <title>
//     commits what changed in <website-dir> to <branch>, pushes it and opens a pull request
//     unless one is open (SITE_REPO_TOKEN: contents + pull requests write on the website repo).
//
// DRY_RUN=1 prints what would be pushed and requested instead of doing it.
import { execFileSync } from 'node:child_process';
import { copyFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const [mode, website, branch, title] = process.argv.slice(2);
const dry = process.env.DRY_RUN === '1';
const APP = process.env.GITHUB_REPOSITORY ?? 'PartBuddy/partbuddy';
const SITE = 'PartBuddy/partbuddy.github.io';

async function api(path, token, init = {}) {
  const res = await fetch(`https://api.github.com${path}`, {
    ...init,
    headers: { Accept: 'application/vnd.github+json', 'User-Agent': 'partbuddy-site-sync', ...(token ? { Authorization: `Bearer ${token}` } : {}), ...init.headers },
  });
  if (!res.ok) throw new Error(`${init.method ?? 'GET'} ${path}: ${res.status} ${await res.text()}`);
  return res.json();
}

async function content() {
  const data = join(website, 'src', 'data');
  for (const f of ['site-content.json', 'site-content.schema.json']) copyFileSync(join(repo, 'site', f), join(data, f));
  // Published releases only, with the fields src/lib/releases.ts of the website reads.
  const list = await api(`/repos/${APP}/releases?per_page=30`, process.env.GITHUB_TOKEN);
  const releases = list
    .filter((r) => !r.draft)
    .map(({ tag_name, published_at, html_url, body, draft, prerelease, assets }) => ({
      tag_name, published_at, html_url, body, draft, prerelease,
      assets: assets.map(({ name, browser_download_url }) => ({ name, browser_download_url })),
    }));
  writeFileSync(join(data, 'releases.json'), `${JSON.stringify(releases, null, 2)}\n`);
  console.log(`[site-sync] content copied, ${releases.length} releases in the snapshot`);
}

async function pullRequest() {
  if (!branch || !title) throw new Error('usage: pr <website-dir> <branch> <title>');
  const git = (...args) => execFileSync('git', ['-C', website, ...args], { encoding: 'utf8' }).trim();
  git('add', '-A');
  if (!git('status', '--porcelain')) return console.log('[site-sync] nothing changed, no pull request');
  const files = git('diff', '--cached', '--stat');
  if (dry) return console.log(`[site-sync] DRY_RUN: would push ${branch} and open "${title}"\n${files}`);
  git('switch', '-C', branch);
  git('-c', 'user.name=partbuddy-site-sync', '-c', 'user.email=site-sync@users.noreply.github.com', 'commit', '-q', '-m', title);
  const token = process.env.SITE_REPO_TOKEN;
  // The checkout keeps no credentials (persist-credentials: false); the token goes only into this push.
  git('push', '-f', `https://x-access-token:${token}@github.com/${SITE}.git`, `HEAD:refs/heads/${branch}`);
  const [owner] = SITE.split('/');
  const open = await api(`/repos/${SITE}/pulls?state=open&head=${owner}:${branch}`, token);
  if (open.length) return console.log(`[site-sync] updated ${open[0].html_url}`);
  const source = process.env.GITHUB_SERVER_URL ? `${process.env.GITHUB_SERVER_URL}/${APP}/actions/runs/${process.env.GITHUB_RUN_ID}` : APP;
  const pr = await api(`/repos/${SITE}/pulls`, token, {
    method: 'POST',
    body: JSON.stringify({ title, head: branch, base: 'main', body: `Generated by the site-sync workflow of the app repository (${source}).\n\n${'```'}\n${files}\n${'```'}` }),
  });
  console.log(`[site-sync] opened ${pr.html_url}`);
}

if (!website) throw new Error('usage: content <website-dir> | pr <website-dir> <branch> <title>');
if (mode === 'content') await content();
else if (mode === 'pr') await pullRequest();
else throw new Error(`unknown mode ${mode}`);
